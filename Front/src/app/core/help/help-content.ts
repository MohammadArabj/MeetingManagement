/** موضوع صفحه‌ی جاری (از روی آدرس بدون # و query) */
export function findHelpTopic(url: string): HelpTopic {
  const path = (url || '/').split('?')[0].split('#').pop() || '/';
  return HELP_TOPICS.find(t => t.match?.test(path)) ?? HELP_TOPICS[0];
}

/** تب‌های صفحه‌ی جزئیات جلسه (id تب فعال ← موضوع راهنما) */
const MEETING_TAB_TOPICS: Record<string, string> = {
  'navs-meetingContent': 'resolutions-in-meeting',
  'navs-Minutes': 'minutes',
  'navs-followup': 'actions',
  'navs-attendance-announcement': 'meeting-details',
  'navs-agendas': 'meeting-details',
  'navs-Members': 'meeting-details',
};

/** موضوع دقیق‌تر بر اساس بخش فعال صفحه (مثلاً تب فعال جزئیات جلسه) */
export function refineHelpTopic(topic: HelpTopic, doc: Document = document): HelpTopic {
  if (topic.key !== 'meeting-details') return topic;
  const activeTab = doc.querySelector('.tab-content > .tab-pane.active')?.id ?? '';
  const key = MEETING_TAB_TOPICS[activeTab];
  return (key && getHelpTopic(key)) || topic;
}

export function getHelpTopic(key: string): HelpTopic | undefined {
  return HELP_TOPICS.find(t => t.key === key);
}
